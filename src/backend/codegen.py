# Type mapping from Aerix types to C99 standard types
C_TYPE_MAP: Dict[str, str] = {
    "i8": "int8_t",
    "i16": "int16_t",
    "i32": "int32_t",
    "i64": "int64_t",
    "int": "int64_t",
    "u8": "uint8_t",
    "u16": "uint16_t",
    "u32": "uint32_t",
    "u64": "uint64_t",
    "uint": "uint64_t",
    "f32": "float",
    "f64": "double",
    "float": "double",
    "bool": "bool",
    "char": "char",
    "str": "const char*",
    "void": "void",
    "null": "void*",
}


def to_c_type(t_name: str) -> str:
    if t_name.endswith("?"):
        base = t_name[:-1]
        return to_c_type(base)
    if t_name.endswith("*"):
        base = t_name[:-1]
        return f"{to_c_type(base)}*"
    if t_name.startswith("Arx_"):
        return t_name
    return C_TYPE_MAP.get(t_name, f"Arx_{t_name}")


def get_type_alignment_size(t_name: str) -> int:
    """Returns the natural alignment/size requirement in bytes for cache-line struct packing."""
    if t_name.endswith("*") or t_name.endswith("?"):
        return 8
    if t_name in ("i64", "u64", "int", "uint", "f64", "float", "str", "usize"):
        return 8
    if t_name in ("i32", "u32", "f32"):
        return 4
    if t_name in ("i16", "u16"):
        return 2
    if t_name in ("i8", "u8", "bool", "char"):
        return 1
    return 8


def escape_c_string(s: str) -> str:
    res = []
    for ch in s:
        if ch == '\\':
            res.append('\\\\')
        elif ch == '"':
            res.append('\\"')
        elif ch == '\n':
            res.append('\\n')
        elif ch == '\t':
            res.append('\\t')
        elif ch == '\r':
            res.append('\\r')
        elif ch == '\b':
            res.append('\\b')
        elif ch == '\f':
            res.append('\\f')
        elif ch == '\v':
            res.append('\\v')
        elif ch == '\0':
            res.append('\\0')
        else:
            res.append(ch)
    return "".join(res)


class C99CodeGenerator:
    def __init__(self):
        self.code: List[str] = []
        self.forward_decls: List[str] = []
        self.struct_decls: List[str] = []

    def emit(self, line: str = "", indent: int = 0) -> None:
        prefix = "    " * indent if line else ""
        self.code.append(prefix + line)

    def generate(self, module: AIRModule) -> str:
        self.module = module
        self.code = []
        self.forward_decls = []
        self.struct_decls = []

        # --- Standard Runtime Headers ---
        self.emit("/**")
        self.emit(" * Auto-Generated by Aerix Compiler (arxc)")
        self.emit(" * Target: ANSI C99 / C11 Native Executable")
        self.emit(" */")
        self.emit()
        self.emit("#include <aerix_rt.h>")

        # Custom C Includes
        for inc in module.c_includes:
            self.emit(f"#include {inc}")
        self.emit()

        # --- Enum Typedefs & Declarations ---
        for enm in getattr(module, "enums", {}).values():
            self.generate_enum_struct(enm)

        # --- Struct Typedefs & Declarations ---
        for cls in module.classes.values():
            self.generate_class_struct(cls)

        # Forward enum constructor declarations
        for enm in getattr(module, "enums", {}).values():
            for v in enm.variants:
                c_params = [f"{to_c_type(t)} {p}" for p, t in v.fields.items()]
                params_str = ", ".join(c_params) if c_params else "void"
                self.forward_decls.append(f"Arx_{enm.name} Arx_{enm.name}_{v.name}({params_str});")


        # Forward function declarations
        for fn in module.functions.values():
            if fn.name != "main":
                f_types = fn.param_types if hasattr(fn, "param_types") and fn.param_types else ["i64"] * len(fn.params)
                param_strs = [f"{to_c_type(t)} {p}" for p, t in zip(fn.params, f_types)]
                ret_t = to_c_type(fn.return_type)
                self.forward_decls.append(f"{ret_t} arx_{fn.name}({', '.join(param_strs) if param_strs else 'void'});")

        # Forward class method & constructor declarations
        for cls in module.classes.values():
            all_ctors = getattr(cls, "constructors", {})
            if all_ctors:
                for ctor_key, ctor_fn in all_ctors.items():
                    c_types = ctor_fn.param_types[1:] if hasattr(ctor_fn, "param_types") and len(ctor_fn.param_types) > 1 else ["i64"] * len(ctor_fn.params[1:])
                    c_params = [f"Arx_{cls.name}* self"] + [f"{to_c_type(t)} {p}" for p, t in zip(ctor_fn.params[1:], c_types)]
                    ctor_sym = ctor_fn.name if ctor_fn.name.startswith("Arx_") else f"Arx_{cls.name}_{ctor_key}"
                    self.forward_decls.append(f"void {ctor_sym}({', '.join(c_params)});")
            elif cls.constructor:
                ctor_types = cls.constructor.param_types[1:] if hasattr(cls.constructor, "param_types") and len(cls.constructor.param_types) > 1 else ["i64"] * len(cls.constructor.params[1:])
                ctor_params = [f"Arx_{cls.name}* self"] + [f"{to_c_type(t)} {p}" for p, t in zip(cls.constructor.params[1:], ctor_types)]
                self.forward_decls.append(f"void Arx_{cls.name}_init({', '.join(ctor_params)});")
            else:
                self.forward_decls.append(f"void Arx_{cls.name}_init(Arx_{cls.name}* self);")
            if cls.destructor:
                self.forward_decls.append(f"void Arx_{cls.name}_drop(Arx_{cls.name}* self);")
            seen_method_syms = set()
            for method_name, method_fn in cls.methods.items():
                ret_t = to_c_type(method_fn.return_type)
                m_types = method_fn.param_types[1:] if hasattr(method_fn, "param_types") and len(method_fn.param_types) > 1 else ["i64"] * len(method_fn.params[1:])
                param_strs = [f"Arx_{cls.name}* self"] + [f"{to_c_type(t)} {p}" for p, t in zip(method_fn.params[1:], m_types)]
                fn_sym = method_fn.name if method_fn.name.startswith("Arx_") else f"Arx_{cls.name}_{method_name}"
                if fn_sym in seen_method_syms:
                    continue
                seen_method_syms.add(fn_sym)
                self.forward_decls.append(f"{ret_t} {fn_sym}({', '.join(param_strs)});")


        for fwd in self.forward_decls:
            self.emit(fwd)
        if self.forward_decls:
            self.emit()

        # --- Concurrency Worker Trampolines (Phase 19) ---
        self.generate_spawn_trampolines(module)

        # --- Enum Implementations ---
        for enm in getattr(module, "enums", {}).values():
            self.generate_enum_impl(enm)

        # --- Class Methods & Constructors ---
        for cls in module.classes.values():
            self.generate_class_impl(cls)


        # --- Global Functions ---
        has_main = False
        for fn in module.functions.values():
            if fn.name == "main":
                has_main = True
                self.generate_main_function(fn)
            else:
                self.generate_function(fn)

        # If no main function, provide default entrypoint
        if not has_main:
            self.emit("int main(int argc, char** argv) {")
            self.emit("    (void)argc; (void)argv;", indent=1)
            self.emit("    return 0;", indent=1)
            self.emit("}")

        return "\n".join(self.code)

    def generate_enum_struct(self, enm: AIREnum) -> None:
        self.emit(f"typedef enum {{")
        for v in enm.variants:
            self.emit(f"    Arx_{enm.name}_{v.name}_Tag,", indent=1)
        self.emit(f"}} Arx_{enm.name}_Tag;")
        self.emit()
        self.emit(f"typedef struct Arx_{enm.name} Arx_{enm.name};")
        self.emit(f"struct Arx_{enm.name} {{")
        self.emit(f"    uint8_t tag;", indent=1)
        has_payload = any(bool(v.fields) for v in enm.variants)
        if has_payload:
            self.emit(f"    union {{", indent=1)
            for v in enm.variants:
                if v.fields:
                    sorted_v_fields = sorted(
                        v.fields.items(),
                        key=lambda item: get_type_alignment_size(item[1]),
                        reverse=True
                    )
                    f_decls = [f"{to_c_type(t)} {p};" for p, t in sorted_v_fields]
                    self.emit(f"        struct {{ {' '.join(f_decls)} }} {v.name};", indent=1)
            self.emit(f"    }} data;", indent=1)
        self.emit(f"}};")
        self.emit()

    def generate_enum_impl(self, enm: AIREnum) -> None:
        for v in enm.variants:
            c_params = [f"{to_c_type(t)} {p}" for p, t in v.fields.items()]
            params_str = ", ".join(c_params) if c_params else "void"
            self.emit(f"Arx_{enm.name} Arx_{enm.name}_{v.name}({params_str}) {{")
            self.emit(f"    Arx_{enm.name} res;", indent=1)
            self.emit(f"    memset(&res, 0, sizeof(Arx_{enm.name}));", indent=1)
            self.emit(f"    res.tag = {v.tag};", indent=1)
            for p in v.fields.keys():
                self.emit(f"    res.data.{v.name}.{p} = {p};", indent=1)
            self.emit(f"    return res;", indent=1)
            self.emit(f"}}")
            self.emit()

    def generate_class_struct(self, cls: AIRClass) -> None:
        self.emit(f"typedef struct Arx_{cls.name} Arx_{cls.name};")
        self.emit(f"struct Arx_{cls.name} {{")
        if cls.base_class:
            self.emit(f"    Arx_{cls.base_class} base;", indent=1)
        # Phase 14: Automatic Cache-Line Struct Packing (descending alignment: 8B -> 4B -> 2B -> 1B)
        sorted_fields = sorted(
            cls.fields.items(),
            key=lambda item: get_type_alignment_size(item[1]),
            reverse=True
        )
        for field_name, field_type in sorted_fields:
            c_type = to_c_type(field_type)
            self.emit(f"    {c_type} {field_name};", indent=1)
        if not cls.fields and not cls.base_class:
            self.emit("    char __dummy;", indent=1) # Prevent empty struct warning
        self.emit("};")
        self.emit()

    def generate_class_impl(self, cls: AIRClass) -> None:
        # Constructors
        all_ctors = getattr(cls, "constructors", {})
        if all_ctors:
            for ctor_key, ctor_fn in all_ctors.items():
                ctor_types = ctor_fn.param_types[1:] if hasattr(ctor_fn, "param_types") and len(ctor_fn.param_types) > 1 else ["i64"] * len(ctor_fn.params[1:])
                ctor_params = [f"Arx_{cls.name}* self"] + [f"{to_c_type(t)} {p}" for p, t in zip(ctor_fn.params[1:], ctor_types)]
                ctor_sym = ctor_fn.name if ctor_fn.name.startswith("Arx_") else f"Arx_{cls.name}_{ctor_key}"
                self.emit(f"void {ctor_sym}({', '.join(ctor_params)}) {{")
                self.generate_function_body(ctor_fn.instructions, indent=1, fn=ctor_fn)
                self.emit("}")
                self.emit()
        elif cls.constructor:
            ctor_types = cls.constructor.param_types[1:] if hasattr(cls.constructor, "param_types") and len(cls.constructor.param_types) > 1 else ["i64"] * len(cls.constructor.params[1:])
            ctor_params = [f"Arx_{cls.name}* self"] + [f"{to_c_type(t)} {p}" for p, t in zip(cls.constructor.params[1:], ctor_types)]
            self.emit(f"void Arx_{cls.name}_init({', '.join(ctor_params)}) {{")
            self.generate_function_body(cls.constructor.instructions, indent=1, fn=cls.constructor)
            self.emit("}")
            self.emit()
        else:
            self.emit(f"void Arx_{cls.name}_init(Arx_{cls.name}* self) {{")
            self.emit(f"    memset(self, 0, sizeof(Arx_{cls.name}));", indent=1)
            self.emit("}")
            self.emit()

        # Destructor
        if cls.destructor:
            self.emit(f"void Arx_{cls.name}_drop(Arx_{cls.name}* self) {{")
            self.generate_function_body(cls.destructor.instructions, indent=1, fn=cls.destructor)
            self.emit("}")
            self.emit()

        seen_impl_syms = set()
        for method_name, method_fn in cls.methods.items():
            ret_t = to_c_type(method_fn.return_type)
            m_types = method_fn.param_types[1:] if hasattr(method_fn, "param_types") and len(method_fn.param_types) > 1 else ["i64"] * len(method_fn.params[1:])
            param_strs = [f"Arx_{cls.name}* self"] + [f"{to_c_type(t)} {p}" for p, t in zip(method_fn.params[1:], m_types)]
            fn_sym = method_fn.name if method_fn.name.startswith("Arx_") else f"Arx_{cls.name}_{method_name}"
            if fn_sym in seen_impl_syms:
                continue
            seen_impl_syms.add(fn_sym)
            self.emit(f"{ret_t} {fn_sym}({', '.join(param_strs)}) {{")
            self.generate_function_body(method_fn.instructions, indent=1, fn=method_fn)
            self.emit("}")
            self.emit()


    def generate_function(self, fn: AIRFunction) -> None:
        ret_t = to_c_type(fn.return_type)
        f_types = fn.param_types if hasattr(fn, "param_types") and fn.param_types else ["i64"] * len(fn.params)
        param_strs = [f"{to_c_type(t)} {p}" for p, t in zip(fn.params, f_types)]
        params_decl = ", ".join(param_strs) if param_strs else "void"
        self.emit(f"{ret_t} arx_{fn.name}({params_decl}) {{")
        self.generate_function_body(fn.instructions, indent=1, fn=fn)
        self.emit("}")
        self.emit()

    def generate_main_function(self, fn: AIRFunction) -> None:
        self.emit("int main(int argc, char** argv) {")
        self.emit("    (void)argc; (void)argv;", indent=1)
        self.generate_function_body(fn.instructions, indent=1, is_main=True, fn=fn)
        self.emit("}")
        self.emit()

    def generate_function_body(self, instructions: List[AIRInstruction], indent: int, is_main: bool = False, fn: Optional[AIRFunction] = None) -> None:
        # Collect all local temporaries and variables for declaration
        temps: Dict[str, str] = {}
        var_types_map: Dict[str, str] = {}

        if fn and hasattr(fn, "var_types") and fn.var_types:
            for v_name, v_type in fn.var_types.items():
                if v_name != "self":
                    var_types_map[v_name] = to_c_type(v_type)

        for _ in range(3):
            for insn in instructions:
                if hasattr(insn, "dest") and insn.dest and not insn.dest.startswith("self."):
                    if isinstance(insn, AIRConst):
                        temps[insn.dest] = to_c_type(insn.type_name)
                    elif isinstance(insn, AIRFormatString):
                        temps[insn.dest] = "const char*"
                    elif isinstance(insn, AIRCallConstructor):
                        temps[insn.dest] = f"Arx_{insn.class_name}"
                    elif isinstance(insn, AIRCall):
                        if insn.fn_name.startswith("arx_input") or insn.fn_name.startswith("arx_readln"):
                            if "int" in insn.fn_name:
                                temps[insn.dest] = "int64_t"
                            elif "uint" in insn.fn_name:
                                temps[insn.dest] = "uint64_t"
                            elif "float" in insn.fn_name:
                                temps[insn.dest] = "double"
                            elif "bool" in insn.fn_name:
                                temps[insn.dest] = "bool"
                            elif "char" in insn.fn_name:
                                temps[insn.dest] = "char"
                            else:
                                temps[insn.dest] = "const char*"
                        elif insn.fn_name in ("input", "readln"):
                            temps[insn.dest] = "const char*"
                        elif insn.fn_name == "arx_time_now":
                            temps[insn.dest] = "double"
                        elif insn.fn_name in ("arx_str_trim", "arx_str_to_upper", "arx_str_to_lower", "arx_str_replace", "arx_str_copy", "arx_str_slice", "arx_str_join", "arx_list_get_str", "arx_list_pop_str"):
                            temps[insn.dest] = "const char*"
                        elif insn.fn_name in ("arx_str_contains", "arx_str_starts_with", "arx_str_ends_with"):
                            temps[insn.dest] = "bool"
                        elif insn.fn_name in ("arx_str_len", "arx_list_len", "arx_list_get_i64", "arx_list_pop_i64", "arx_str_split"):
                            temps[insn.dest] = "int64_t"
                        elif insn.fn_name in ("arx_list_get_f64", "arx_list_pop_f64"):
                            temps[insn.dest] = "double"
                        else:
                            ret_t = "int64_t"
                            is_enum_ctor = False
                            if hasattr(self, "module") and self.module:
                                for enm in getattr(self.module, "enums", {}).values():
                                    for v in enm.variants:
                                        if insn.fn_name == f"Arx_{enm.name}_{v.name}":
                                            ret_t = f"Arx_{enm.name}"
                                            is_enum_ctor = True
                                            break
                                    if is_enum_ctor:
                                        break
                                if not is_enum_ctor and insn.fn_name in self.module.functions:
                                    ret_t = to_c_type(self.module.functions[insn.fn_name].return_type)
                            temps[insn.dest] = ret_t
                    elif isinstance(insn, AIRGetPayloadField):
                        field_t = "int64_t"
                        if hasattr(self, "module") and self.module:
                            for enm in getattr(self.module, "enums", {}).values():
                                for v in enm.variants:
                                    if v.name == insn.variant_name and insn.field_name in v.fields:
                                        field_t = to_c_type(v.fields[insn.field_name])
                                        break
                        temps[insn.dest] = field_t
                    elif isinstance(insn, AIRSpawn):
                        if insn.dest:
                            temps[insn.dest] = "int64_t"
                    elif isinstance(insn, AIRCallMethod):
                        if insn.dest:
                            ret_t = "int64_t"
                            cls_name = insn.class_name
                            if not cls_name or cls_name == "Class":
                                if fn and hasattr(fn, "var_types") and insn.instance in fn.var_types:
                                    cls_name = fn.var_types[insn.instance]
                            if cls_name.startswith("List_") and insn.method_name == "slice":
                                ret_t = f"Arx_{cls_name}"
                            elif cls_name == "List_str" and insn.method_name in ("get", "pop"):
                                ret_t = "const char*"
                            elif cls_name == "List_f64" and insn.method_name in ("get", "pop"):
                                ret_t = "double"
                            elif insn.method_name == "as_str":
                                ret_t = "const char*"
                            elif hasattr(self, "module") and self.module and cls_name in self.module.classes:
                                cls = self.module.classes[cls_name]
                                if insn.method_name in cls.methods:
                                    ret_t = to_c_type(cls.methods[insn.method_name].return_type)
                                else:
                                    for m_name, m_fn in cls.methods.items():
                                        if m_name == insn.method_name or m_fn.name == insn.method_name or m_name == f"Arx_{cls_name}_{insn.method_name}":
                                            ret_t = to_c_type(m_fn.return_type)
                                            break
                            temps[insn.dest] = ret_t

                    elif isinstance(insn, AIRGetField):
                        field_t = "int64_t"
                        inst_cls = None
                        if fn and hasattr(fn, "var_types") and insn.instance in fn.var_types:
                            inst_cls = fn.var_types[insn.instance]
                        elif insn.instance in var_types_map:
                            inst_cls = var_types_map[insn.instance].replace("Arx_", "")
                        elif insn.instance in temps:
                            inst_cls = temps[insn.instance].replace("Arx_", "")

                        if inst_cls and hasattr(self, "module") and self.module and inst_cls in self.module.classes:
                            cls = self.module.classes[inst_cls]
                            if insn.field_name in cls.fields:
                                field_t = to_c_type(cls.fields[insn.field_name])
                        elif hasattr(self, "module") and self.module:
                            for cls in self.module.classes.values():
                                if insn.field_name in cls.fields:
                                    field_t = to_c_type(cls.fields[insn.field_name])
                                    break
                        temps[insn.dest] = field_t
                    elif isinstance(insn, AIRCast):
                        temps[insn.dest] = to_c_type(insn.target_type)
                    elif isinstance(insn, AIRLoad):
                        if insn.var_name in var_types_map:
                            temps[insn.dest] = var_types_map[insn.var_name]
                        elif insn.dest not in temps:
                            temps[insn.dest] = "int64_t"
                    elif isinstance(insn, AIRBinOp):
                        l_t = temps.get(insn.left, "int64_t")
                        r_t = temps.get(insn.right, "int64_t")
                        if insn.op in ("<", "<=", ">", ">=", "==", "!=", "&&", "||"):
                            temps[insn.dest] = "bool"
                        elif l_t in ("float", "double") or r_t in ("float", "double"):
                            temps[insn.dest] = "double"
                        else:
                            temps[insn.dest] = "int64_t"
                    elif insn.dest not in temps:
                        temps[insn.dest] = "int64_t"
                if isinstance(insn, AIRStore):
                    if insn.src in temps:
                        var_types_map[insn.var_name] = temps[insn.src]
                    elif insn.var_name not in var_types_map:
                        var_types_map[insn.var_name] = "int64_t"

        # Emit variable declarations at the top of the function
        params_set = set(fn.params) if (fn and hasattr(fn, "params")) else set()
        for var_name in sorted(var_types_map.keys()):
            if var_name != "self" and var_name not in params_set:
                v_type = var_types_map[var_name]
                if v_type.startswith("Arx_"):
                    self.emit(f"{v_type} {var_name};", indent=indent)
                else:
                    self.emit(f"{v_type} {var_name} = 0;", indent=indent)
        for t_name, t_type in sorted(temps.items()):
            if t_type.startswith("Arx_"):
                self.emit(f"{t_type} {t_name};", indent=indent)
            else:
                self.emit(f"{t_type} {t_name} = 0;", indent=indent)

        if temps or var_types_map:
            self.emit()

        # Emit instructions
        for insn in instructions:
            if isinstance(insn, AIRDeferPush):
                pass
            elif isinstance(insn, AIRConst):
                val_str = self.format_constant(insn.value, insn.type_name)
                self.emit(f"{insn.dest} = {val_str};", indent=indent)
            elif isinstance(insn, AIRFormatString):
                fmt_escaped = escape_c_string(insn.fmt)
                fmt_args = []
                for a in insn.args:
                    t_a = temps.get(a, "")
                    if t_a == "bool":
                        fmt_args.append(f'(({a}) ? "true" : "false")')
                    elif t_a in ("String", "Arx_String"):
                        fmt_args.append(f"{a}.buf")
                    else:
                        fmt_args.append(a)
                args_part = f", {', '.join(fmt_args)}" if fmt_args else ""
                self.emit(f'{insn.dest} = arx_format_str("{fmt_escaped}"{args_part});', indent=indent)
            elif isinstance(insn, AIRCast):
                target_t = insn.target_type
                src_t = getattr(insn, "src_type", "unknown")
                c_type = to_c_type(target_t)
                src_c = temps.get(insn.src, "")

                if src_t == "str" or src_c in ("const char*", "char*"):
                    if target_t in ("i8", "i16", "i32", "i64", "int"):
                        self.emit(f"{insn.dest} = ({c_type})arx_cast_to_i64({insn.src});", indent=indent)
                    elif target_t in ("u8", "u16", "u32", "u64", "uint"):
                        self.emit(f"{insn.dest} = ({c_type})arx_cast_to_u64({insn.src});", indent=indent)
                    elif target_t in ("f32", "f64", "float"):
                        self.emit(f"{insn.dest} = ({c_type})arx_cast_to_f64({insn.src});", indent=indent)
                    elif target_t == "bool":
                        self.emit(f"{insn.dest} = arx_cast_to_bool({insn.src});", indent=indent)
                    elif target_t == "char":
                        self.emit(f"{insn.dest} = ({insn.src} && {insn.src}[0]) ? {insn.src}[0] : '\\0';", indent=indent)
                    else:
                        self.emit(f"{insn.dest} = ({c_type})({insn.src});", indent=indent)
                elif target_t == "str":
                    if src_t in ("i8", "i16", "i32", "i64", "int") or src_c in ("int8_t", "int16_t", "int32_t", "int64_t", "int", "long long"):
                        self.emit(f"{insn.dest} = arx_cast_i64_to_str((int64_t)({insn.src}));", indent=indent)
                    elif src_t in ("u8", "u16", "u32", "u64", "uint") or src_c in ("uint8_t", "uint16_t", "uint32_t", "uint64_t"):
                        self.emit(f"{insn.dest} = arx_cast_u64_to_str((uint64_t)({insn.src}));", indent=indent)
                    elif src_t in ("f32", "f64", "float") or src_c in ("float", "double"):
                        self.emit(f"{insn.dest} = arx_cast_f64_to_str((double)({insn.src}));", indent=indent)
                    elif src_t == "bool" or src_c == "bool":
                        self.emit(f"{insn.dest} = arx_cast_bool_to_str({insn.src});", indent=indent)
                    elif src_t == "char" or src_c == "char":
                        self.emit(f"{insn.dest} = arx_cast_char_to_str({insn.src});", indent=indent)
                    else:
                        self.emit(f"{insn.dest} = arx_cast_i64_to_str((int64_t)({insn.src}));", indent=indent)
                else:
                    self.emit(f"{insn.dest} = ({c_type})({insn.src});", indent=indent)
            elif isinstance(insn, AIRCallConstructor):
                args_str = ", ".join([f"&{insn.dest}"] + insn.args)
                ctor_target = insn.ctor_name if (getattr(insn, "ctor_name", None) and insn.ctor_name.startswith("Arx_")) else (
                    f"Arx_{insn.class_name}_{insn.ctor_name}" if getattr(insn, "ctor_name", None) else f"Arx_{insn.class_name}_init"
                )
                self.emit(f"{ctor_target}({args_str});", indent=indent)
            elif isinstance(insn, AIRLoad):
                self.emit(f"{insn.dest} = {insn.var_name};", indent=indent)
            elif isinstance(insn, AIRStore):
                if insn.var_name in var_types_map:
                    v_type = var_types_map[insn.var_name]
                    self.emit(f"{insn.var_name} = ({v_type})({insn.src});", indent=indent)
                else:
                    self.emit(f"{insn.var_name} = {insn.src};", indent=indent)
            elif isinstance(insn, AIRBinOp):
                op_c = insn.op
                if op_c == "**":
                    self.emit(f"{insn.dest} = (int64_t)pow((double){insn.left}, (double){insn.right});", indent=indent)
                else:
                    self.emit(f"{insn.dest} = {insn.left} {op_c} {insn.right};", indent=indent)
            elif isinstance(insn, AIRUnaryOp):
                self.emit(f"{insn.dest} = {insn.op}{insn.operand};", indent=indent)
            elif isinstance(insn, AIRCall):
                self.generate_call_instruction(insn, indent=indent, temps=temps)
            elif isinstance(insn, AIRSpawn):
                self.generate_spawn_instruction(insn, indent=indent, temps=temps)
            elif isinstance(insn, AIRCallMethod):
                inst_ref = insn.instance if insn.instance == "self" else f"&{insn.instance}"
                args_str = ", ".join([inst_ref] + insn.args)
                method_target = insn.method_name if insn.method_name.startswith("Arx_") else f"Arx_{insn.class_name}_{insn.method_name}"
                if insn.dest:
                    self.emit(f"{insn.dest} = {method_target}({args_str});", indent=indent)
                else:
                    self.emit(f"{method_target}({args_str});", indent=indent)
            elif isinstance(insn, AIRGetField):
                access = f"self->{insn.field_name}" if insn.instance == "self" else f"{insn.instance}.{insn.field_name}"
                self.emit(f"{insn.dest} = {access};", indent=indent)
            elif isinstance(insn, AIRGetPayloadField):
                self.emit(f"{insn.dest} = {insn.instance}.data.{insn.variant_name}.{insn.field_name};", indent=indent)
            elif isinstance(insn, AIRSetField):

                access = f"self->{insn.field_name}" if insn.instance == "self" else f"{insn.instance}.{insn.field_name}"
                self.emit(f"{access} = {insn.value};", indent=indent)
            elif isinstance(insn, AIRBranchIfNot):
                self.emit(f"if (!({insn.condition})) goto {insn.target_label};", indent=indent)
            elif isinstance(insn, AIRBranchIf):
                self.emit(f"if ({insn.condition}) goto {insn.target_label};", indent=indent)
            elif isinstance(insn, AIRJump):
                self.emit(f"goto {insn.target_label};", indent=indent)
            elif isinstance(insn, AIRLabel):
                self.emit(f"{insn.name}:", indent=max(0, indent - 1))
            elif isinstance(insn, AIRReturn):
                if is_main:
                    self.emit(f"return {insn.value if insn.value else '0'};", indent=indent)
                elif insn.value:
                    self.emit(f"return {insn.value};", indent=indent)
                else:
                    self.emit("return;", indent=indent)

    def generate_call_instruction(self, insn: AIRCall, indent: int, temps: Optional[Dict[str, str]] = None) -> None:
        t_types = temps or {}
        if insn.fn_name == "println":
            if insn.args:
                arg = insn.args[0]
                t_type = t_types.get(arg, "int64_t")
                if t_type in ("const char*", "char*"):
                    self.emit(f'printf("%s\\n", {arg});', indent=indent)
                elif t_type in ("String", "Arx_String"):
                    self.emit(f'printf("%s\\n", {arg}.buf);', indent=indent)
                elif t_type in ("float", "double"):
                    self.emit(f'printf("%g\\n", (double)({arg}));', indent=indent)
                elif t_type == "bool":
                    self.emit(f'printf("%s\\n", ({arg}) ? "true" : "false");', indent=indent)
                else:
                    self.emit(f'printf("%lld\\n", (long long)({arg}));', indent=indent)
            else:
                self.emit("putchar('\\n');", indent=indent)
        elif insn.fn_name == "print":
            if insn.args:
                arg = insn.args[0]
                t_type = t_types.get(arg, "int64_t")
                if t_type in ("const char*", "char*"):
                    self.emit(f'printf("%s", {arg});', indent=indent)
                elif t_type in ("String", "Arx_String"):
                    self.emit(f'printf("%s", {arg}.buf);', indent=indent)
                elif t_type in ("float", "double"):
                    self.emit(f'printf("%g", (double)({arg}));', indent=indent)
                elif t_type == "bool":
                    self.emit(f'printf("%s", ({arg}) ? "true" : "false");', indent=indent)
                else:
                    self.emit(f'printf("%lld", (long long)({arg}));', indent=indent)
        elif insn.fn_name.startswith("arx_input"):
            arg_str = insn.args[0] if insn.args else '""'
            if insn.dest:
                self.emit(f"{insn.dest} = {insn.fn_name}({arg_str});", indent=indent)
            else:
                self.emit(f"{insn.fn_name}({arg_str});", indent=indent)
        elif insn.fn_name.startswith("arx_readln"):
            if insn.dest:
                self.emit(f"{insn.dest} = {insn.fn_name}();", indent=indent)
            else:
                self.emit(f"{insn.fn_name}();", indent=indent)
        elif insn.fn_name in ("input", "readln"):
            arg_str = insn.args[0] if insn.args else '""'
            if insn.dest:
                self.emit(f"{insn.dest} = arx_input({arg_str});", indent=indent)
            else:
                self.emit(f"arx_input({arg_str});", indent=indent)
        elif insn.fn_name == "arx_time_now":
            if insn.dest:
                self.emit(f"{insn.dest} = arx_time_now();", indent=indent)
        else:
            prefix = "" if (insn.fn_name.startswith("arx_") or insn.fn_name.startswith("Arx_")) else "arx_"
            c_fn = f"{prefix}{insn.fn_name}"
            args_str = ", ".join(insn.args)
            if insn.dest:
                self.emit(f"{insn.dest} = {c_fn}({args_str});", indent=indent)
            else:
                self.emit(f"{c_fn}({args_str});", indent=indent)

    def get_c_fn_info(self, fn_name: str) -> Tuple[str, List[str]]:
        raw_name = fn_name
        if raw_name.startswith("arx_"):
            raw_name = raw_name[4:]
        c_fn = fn_name if (fn_name.startswith("arx_") or fn_name.startswith("Arx_")) else f"arx_{fn_name}"
        param_types: List[str] = []
        if hasattr(self, "module") and self.module:
            if raw_name in self.module.functions:
                param_types = getattr(self.module.functions[raw_name], "param_types", []) or []
            elif fn_name in self.module.functions:
                param_types = getattr(self.module.functions[fn_name], "param_types", []) or []
        return c_fn, param_types

    def generate_spawn_trampolines(self, module: AIRModule) -> None:
        spawned: Dict[str, Tuple[str, List[str]]] = {}
        all_insns: List[AIRInstruction] = []
        for fn in module.functions.values():
            all_insns.extend(fn.instructions)
        for cls in module.classes.values():
            for ctor in getattr(cls, "constructors", {}).values():
                all_insns.extend(ctor.instructions)
            if cls.constructor:
                all_insns.extend(cls.constructor.instructions)
            if cls.destructor:
                all_insns.extend(cls.destructor.instructions)
            for m in cls.methods.values():
                all_insns.extend(m.instructions)

        for insn in all_insns:
            if isinstance(insn, AIRSpawn):
                c_fn, param_types = self.get_c_fn_info(insn.fn_name)
                arity = len(insn.args)
                key = f"{c_fn}_{arity}"
                if key not in spawned:
                    spawned[key] = (c_fn, param_types[:arity])

        if not spawned:
            return

        self.emit("// --- Concurrency Worker Trampolines (Phase 19) ---")
        for key, (c_fn, p_types) in spawned.items():
            arity = int(key.split("_")[-1])
            tramp_name = f"arx_trampoline_{key}"
            if arity == 0:
                self.emit(f"static void* {tramp_name}(void* arg) {{")
                self.emit("    (void)arg;", indent=1)
                self.emit(f"    {c_fn}();", indent=1)
                self.emit("    return NULL;", indent=1)
                self.emit("}")
                self.emit()
            elif arity == 1:
                t0 = p_types[0] if p_types else "i64"
                c_t0 = to_c_type(t0)
                cast_expr = f"({c_t0})arg" if (c_t0.endswith("*") or c_t0 in ("const char*", "char*", "void*")) else f"({c_t0})(intptr_t)arg"
                self.emit(f"static void* {tramp_name}(void* arg) {{")
                self.emit(f"    {c_fn}({cast_expr});", indent=1)
                self.emit("    return NULL;", indent=1)
                self.emit("}")
                self.emit()
            else:
                pack_name = f"Arx_ArgPack_{key}"
                self.emit(f"typedef struct {pack_name} {{")
                for i in range(arity):
                    t_i = p_types[i] if i < len(p_types) else "i64"
                    c_ti = to_c_type(t_i)
                    self.emit(f"    {c_ti} arg{i};", indent=1)
                self.emit(f"}} {pack_name};")
                self.emit(f"static void* {tramp_name}(void* arg) {{")
                self.emit(f"    {pack_name}* pack = ({pack_name}*)arg;", indent=1)
                call_args = ", ".join([f"pack->arg{i}" for i in range(arity)])
                self.emit(f"    {c_fn}({call_args});", indent=1)
                self.emit("    arx_free(pack);", indent=1)
                self.emit("    return NULL;", indent=1)
                self.emit("}")
                self.emit()

    def generate_spawn_instruction(self, insn: AIRSpawn, indent: int, temps: Optional[Dict[str, str]] = None) -> None:
        c_fn, param_types = self.get_c_fn_info(insn.fn_name)
        arity = len(insn.args)
        key = f"{c_fn}_{arity}"
        tramp_name = f"arx_trampoline_{key}"
        if arity == 0:
            call_expr = f"arx_thread_spawn({tramp_name}, NULL)"
            if insn.dest:
                self.emit(f"{insn.dest} = {call_expr};", indent=indent)
            else:
                self.emit(f"(void){call_expr};", indent=indent)
        elif arity == 1:
            arg0 = insn.args[0]
            t0 = param_types[0] if param_types else "i64"
            c_t0 = to_c_type(t0)
            arg_cast = f"(void*){arg0}" if (c_t0.endswith("*") or c_t0 in ("const char*", "char*", "void*")) else f"(void*)(intptr_t){arg0}"
            call_expr = f"arx_thread_spawn({tramp_name}, {arg_cast})"
            if insn.dest:
                self.emit(f"{insn.dest} = {call_expr};", indent=indent)
            else:
                self.emit(f"(void){call_expr};", indent=indent)
        else:
            pack_name = f"Arx_ArgPack_{key}"
            self.emit("{", indent=indent)
            self.emit(f"{pack_name}* __pack = ({pack_name}*)arx_alloc(sizeof({pack_name}));", indent=indent + 1)
            for idx, a in enumerate(insn.args):
                self.emit(f"__pack->arg{idx} = {a};", indent=indent + 1)
            call_expr = f"arx_thread_spawn({tramp_name}, (void*)__pack)"
            if insn.dest:
                self.emit(f"{insn.dest} = {call_expr};", indent=indent + 1)
            else:
                self.emit(f"(void){call_expr};", indent=indent + 1)
            self.emit("}", indent=indent)

    def format_constant(self, val: Any, type_name: str) -> str:
        if type_name == "str":
            return f'"{escape_c_string(str(val))}"'
        elif type_name == "bool":
            return "true" if val else "false"
        elif type_name in ("f32", "f64"):
            return str(float(val))
        elif type_name == "char":
            return f"'{escape_c_string(str(val))}'"
        elif type_name == "null":
            return "NULL"
        return str(val)

