def to_c_type(t_name: str) -> str:
    if t_name.endswith("?"):
        base = t_name[:-1]
        return to_c_type(base)
    if t_name.endswith("*"):
        base = t_name[:-1]
        return f"{to_c_type(base)}*"
    # Phase 23: FixedArray_<elem>_<N> -> pointer in C (for params/returns)
    if t_name.startswith("FixedArray_"):
        parts = t_name.split("_")
        if len(parts) >= 3:
            elem_name = "_".join(parts[1:-1])
            return f"{to_c_type(elem_name)}*"
        return "int64_t*"
    # Feature 3: Slice types -> Arx_Slice
    if t_name.startswith("Slice_"):
        return "Arx_Slice"
    # Feature 5: Function pointer types
    if t_name.startswith("Fn_"):
        return t_name
    if t_name.startswith("Arx_"):
        return t_name
    return C_TYPE_MAP.get(t_name, f"Arx_{t_name}")


def get_type_alignment_size(t_name: str) -> int:
    """Returns the natural alignment/size requirement in bytes for cache-line struct packing."""
    if t_name in ("f32x4", "f64x2"):
        return 16
    if t_name.endswith("*") or t_name.endswith("?"):
        return 8
    if t_name in ("i64", "u64", "int", "uint", "f64", "float", "str", "usize"):
        return 8
    if t_name in ("i32", "u32", "f32"):
        return 4
    if t_name in ("i16", "u16"):
        return 2
    if t_name in ("i8", "u8", "bool", "char"):
        return 1
    return 8


def escape_c_string(s: str) -> str:
    res = []
    for ch in s:
        if ch == '\\':
            res.append('\\\\')
        elif ch == '"':
            res.append('\\"')
        elif ch == '\n':
            res.append('\\n')
        elif ch == '\t':
            res.append('\\t')
        elif ch == '\r':
            res.append('\\r')
        elif ch == '\b':
            res.append('\\b')
        elif ch == '\f':
            res.append('\\f')
        elif ch == '\v':
            res.append('\\v')
        elif ch == '\0':
            res.append('\\0')
        else:
            res.append(ch)
    return "".join(res)


